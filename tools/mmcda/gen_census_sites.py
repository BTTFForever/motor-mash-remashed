"""Generate census_sites.h: every indirect call `call dword ptr [reg+disp]` in MotorMsh.exe.

These are the game's COM method calls (reg holds the vtable, disp/4 is the slot). census.h
puts a one-shot breakpoint on each to learn which DirectX interfaces and methods the game uses.
Input: a dumpbin /disasm of your own MotorMsh.exe (tools/sixcars/MotorMsh.dis.txt, not in git).
Usage: python -I gen_census_sites.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DIS = os.path.join(HERE, "..", "sixcars", "MotorMsh.dis.txt")
REGS = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"]
pat = re.compile(r"^  ([0-9A-F]{8}): call +dword ptr \[(e[a-z]{2})(?:\+([0-9A-F]+)h)?\]\s*$")

sites = []
for line in open(DIS):
    m = pat.match(line)
    if not m or m.group(2) == "esp":
        continue
    sites.append((int(m.group(1), 16), REGS.index(m.group(2)), int(m.group(3) or "0", 16)))

with open(os.path.join(HERE, "census_sites.h"), "w") as f:
    f.write("/* generated by gen_census_sites.py: game call sites of the form call [reg+disp] */\n")
    f.write("#define CENSUS_NSITES %d\n" % len(sites))
    f.write("static const struct { DWORD addr; BYTE reg; WORD disp; } k_census_sites[CENSUS_NSITES] = {\n")
    for a, r, d in sites:
        f.write("    { 0x%06X, %d, 0x%X },\n" % (a, r, d))
    f.write("};\n")
print(len(sites), "sites")
