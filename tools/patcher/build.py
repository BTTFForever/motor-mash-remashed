"""Build MotorMashPatch.exe (the release patcher) with MSVC (x86).

Embeds only the port's own files and redistributable third-party components:
  MMCDA.dll (tools/mmcda), SDL3.dll (zlib licence), dgVoodoo2 DDraw.dll / D3DImm.dll
  (unmodified, shipped with a game mod as its readme allows) and dgVoodoo.conf.
Nothing from the game itself: the patcher patches the player's own MotorMsh.exe and copies
the DirectX 5 files and music from the player's own CD.

Usage: python -I build.py            -> tools/patcher/MotorMashPatch.exe
Needs tools/mmcda/MMCDA.dll built and tools/dgVoodoo2 extracted from dgVoodoo2_87_6.zip.
"""
import os, subprocess, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
VCVARS = r"C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars32.bat"

# (resource id, installed name, source, keep an existing copy)
PAYLOAD = [
    (101, "MMCDA.dll", os.path.join(TOOLS, "mmcda", "MMCDA.dll"), 0),
    (102, "SDL3.dll", os.path.join(TOOLS, "mmcda", "third_party", "SDL3", "SDL3-3.4.20", "lib", "x86", "SDL3.dll"), 0),
    (103, "DDraw.dll", os.path.join(TOOLS, "dgVoodoo2", "MS", "x86", "DDraw.dll"), 0),
    (104, "D3DImm.dll", os.path.join(TOOLS, "dgVoodoo2", "MS", "x86", "D3DImm.dll"), 0),
    (105, "dgVoodoo.conf", os.path.join(HERE, "dgVoodoo.conf"), 1),
]


def ensure_dgvoodoo():
    if os.path.exists(PAYLOAD[2][2]):
        return
    with zipfile.ZipFile(os.path.join(TOOLS, "dgVoodoo2_87_6.zip")) as z:
        z.extractall(os.path.join(TOOLS, "dgVoodoo2"))


def main():
    ensure_dgvoodoo()
    for _, name, src, _ in PAYLOAD:
        if not os.path.exists(src):
            sys.exit(f"missing {name}: {src}")
    with open(os.path.join(HERE, "payload.h"), "w") as f:
        f.write("/* generated by build.py */\n#define PAYLOAD_COUNT %d\n" % len(PAYLOAD))
        f.write("static const struct { int id; const char *name; int keep; } k_payload[PAYLOAD_COUNT] = {\n")
        for rid, name, _, keep in PAYLOAD:
            f.write('    { %d, "%s", %d },\n' % (rid, name, keep))
        f.write("};\n")
    with open(os.path.join(HERE, "patcher.rc"), "w") as f:
        for rid, _, src, _ in PAYLOAD:
            f.write('%d RCDATA "%s"\n' % (rid, src.replace("\\", "\\\\")))
        f.write('1 24 "%s"\n' % os.path.join(HERE, "patcher.manifest").replace("\\", "\\\\"))   # RT_MANIFEST
        # no icon: the game's own icon is game content and stays out of the release
    bat = os.path.join(HERE, "_build.bat")
    with open(bat, "w") as f:
        f.write('@echo off\ncall "%s" >nul\ncd /d "%s"\n' % (VCVARS, HERE))
        f.write("rc /nologo patcher.rc || exit /b 1\n")
        f.write("cl /nologo /O2 /W3 /MT patcher.c patcher.res /link /OUT:MotorMashPatch.exe "
                "bcrypt.lib shell32.lib ole32.lib uuid.lib user32.lib || exit /b 1\n")
    subprocess.run(["cmd", "/c", bat], check=True)
    print("built", os.path.join(HERE, "MotorMashPatch.exe"),
          os.path.getsize(os.path.join(HERE, "MotorMashPatch.exe")), "bytes")


if __name__ == "__main__":
    main()
