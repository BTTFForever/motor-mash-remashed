"""Build MotorMash.exe (single-file launcher) from the project folder.

Stages the payload, extracts the game's icon, generates payload.h / payload.rc with a
content-hash build id, then compiles with MSVC (x86).

Usage (from anywhere):  python -I build.py
Output: tools/launcher/MotorMash.exe
"""
import hashlib, os, shutil, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))           # Motor Mash/
TOOLS = os.path.join(ROOT, "tools")
GAME = os.path.join(ROOT, "game")
STAGE = os.path.join(HERE, "payload")
VCVARS = r"C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars32.bat"

def stage():
    if os.path.isdir(STAGE):
        shutil.rmtree(STAGE)
    os.makedirs(os.path.join(STAGE, "Music"))
    # patched game exe, regenerated from the untouched disc original
    exe = os.path.join(STAGE, "MotorMsh.exe")
    shutil.copyfile(os.path.join(ROOT, "extracted", "MotorMsh.exe"), exe)
    subprocess.run([sys.executable, "-I", os.path.join(TOOLS, "patch_motormsh.py"), exe], check=True)
    files = {
        "MMCDA.dll": os.path.join(TOOLS, "mmcda", "MMCDA.dll"),
        "DDraw.dll": os.path.join(TOOLS, "dgVoodoo2", "MS", "x86", "DDraw.dll"),
        "D3DImm.dll": os.path.join(TOOLS, "dgVoodoo2", "MS", "x86", "D3DImm.dll"),
        "dgVoodoo.conf": os.path.join(GAME, "dgVoodoo.conf"),
        # SDL3 (x86) for native controller support; MMCDA.dll loads it at run time
        "SDL3.dll": os.path.join(TOOLS, "mmcda", "third_party", "SDL3", "SDL3-3.4.20", "lib", "x86", "SDL3.dll"),
    }
    for n in ("d3drm.dll", "d3drm8f.dll", "d3drm16f.dll", "d3drm24f.dll", "d3drm32f.dll", "d3dxof.dll"):
        files[n] = os.path.join(GAME, n)
    for n in sorted(os.listdir(os.path.join(HERE, "music"))):
        if n.lower().endswith(".ogg"):
            files["Music\\" + n] = os.path.join(HERE, "music", n)
    for name, src in files.items():
        shutil.copyfile(src, os.path.join(STAGE, name))
    return ["MotorMsh.exe"] + list(files)

def extract_icon(exe_path, out_ico):
    """Write the exe's first RT_GROUP_ICON as a .ico file."""
    d = open(exe_path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    rsrc_rva = struct.unpack_from("<I", d, pe + 24 + 112)[0]     # data dir 2 (PE32)
    secs = []
    for i in range(nsec):
        o = pe + 24 + opt + 40 * i
        secs.append(struct.unpack_from("<IIII", d, o + 8))        # vsize, va, rawsize, rawptr
    def off(rva):
        for vsize, va, rsize, rptr in secs:
            if va <= rva < va + max(vsize, rsize):
                return rva - va + rptr
        raise ValueError(hex(rva))
    base = off(rsrc_rva)
    def entries(o):
        nn, ni = struct.unpack_from("<HH", d, base + o + 12)
        for i in range(nn + ni):
            yield struct.unpack_from("<II", d, base + o + 16 + 8 * i)
    def leaf(o):
        while o & 0x80000000:
            o = next(entries(o & 0x7FFFFFFF))[1]
        rva, size = struct.unpack_from("<II", d, base + o)
        return d[off(rva):off(rva) + size]
    types = {t: p for t, p in entries(0)}
    icons = {}
    for name, p in entries(types[3] & 0x7FFFFFFF):
        icons[name] = leaf(p)
    group = leaf(next(entries(types[14] & 0x7FFFFFFF))[1])
    count = struct.unpack_from("<H", group, 4)[0]
    out = struct.pack("<HHH", 0, 1, count)
    data, pos = b"", 6 + 16 * count
    for i in range(count):
        w, h, cc, r, planes, bpp, size, nid = struct.unpack_from("<BBBBHHIH", group, 6 + 14 * i)
        img = icons[nid]
        out += struct.pack("<BBBBHHII", w, h, cc, r, planes, bpp, len(img), pos + len(data))
        data += img
    open(out_ico, "wb").write(out + data)

def main():
    names = stage()
    h = hashlib.sha256()
    for n in names:
        h.update(n.encode()); h.update(open(os.path.join(STAGE, n), "rb").read())
    build_id = "build-" + h.hexdigest()[:12]
    extract_icon(os.path.join(ROOT, "extracted", "MotorMsh.exe"), os.path.join(HERE, "motormash.ico"))
    with open(os.path.join(HERE, "payload.h"), "w") as f:
        f.write("/* generated by build.py */\n")
        f.write(f'#define BUILD_ID L"{build_id}"\n#define PAYLOAD_COUNT {len(names)}\n')
        f.write("static const struct { int id; const wchar_t *name; } g_payload[] = {\n")
        for i, n in enumerate(names):
            f.write(f'    {{ {1000 + i}, L"{n.replace(chr(92), chr(92) * 2)}" }},\n')
        f.write("};\n")
    with open(os.path.join(HERE, "payload.rc"), "w") as f:
        f.write('1 ICON "motormash.ico"\n')
        for i, n in enumerate(names):
            f.write(f'{1000 + i} RCDATA "payload\\\\{n.replace(chr(92), chr(92) * 2)}"\n')
    bat = os.path.join(HERE, "_build.bat")
    with open(bat, "w") as f:
        f.write(f'@echo off\ncall "{VCVARS}" >nul\ncd /d "{HERE}"\n'
                'rc /nologo payload.rc || exit /b 1\n'
                'cl /nologo /O2 /W3 /MT /DUNICODE /D_UNICODE launcher.c payload.res '
                '/link /SUBSYSTEM:WINDOWS /OUT:MotorMash.exe user32.lib shell32.lib ole32.lib || exit /b 1\n')
    r = subprocess.run(["cmd", "/c", bat], capture_output=True, text=True)
    print(r.stdout[-2000:], r.stderr[-2000:])
    if r.returncode:
        sys.exit(r.returncode)
    print(build_id, f"{os.path.getsize(os.path.join(HERE, 'MotorMash.exe')) / 1e6:.1f} MB")

if __name__ == "__main__":
    main()
