"""Generate tools/mmcda/relocs.h: every code site that holds an address inside one of the
game's fixed-size per-car tables (the car records
themselves at 0x632DA0 already have room for 6: 0x633F20-0x6347E0 is unused), so MMCDA can point them at larger copies at start-up.

Usage: python -I gen_relocs.py <MotorMsh.exe> <MotorMsh.dis.txt> <out relocs.h> [--report]

The disassembly is `dumpbin /disasm /nobytes` of the unpatched-code exe (MotorMsh_dbg.exe has
identical code). A value equal to a table's end address is not moved (it is usually the next
global); loop bounds that need the new end are patched by hand in sixcars.h.
"""
import re, struct, sys

# name, old base, element size, old count, new count
TABLES = [
    ('bodymesh',  0x465640, 4, 4, 6),
    ('shadmesh',  0x485BF8, 4, 4, 6),
    ('placed',    0x485C08, 4, 4, 6),
    ('shadframe', 0x485C18, 4, 4, 6),
    ('bodyframe', 0x488568, 4, 4, 6),
    ('sndreq',    0x630A60, 4, 4, 6),
    ('sndplay',   0x637E40, 4, 4, 6),
    ('snd_19e0',  0x6319E0, 4, 4, 6),
    ('snd_1a40',  0x631A40, 4, 4, 6),
    ('snd_25d0',  0x6325D0, 4, 4, 6),
    ('snd_0e00',  0x630E00, 4, 4, 6),
    ('hud',       0x637E80, 0x30, 8, 12),
    ('hudplace',  0x54A228, 4, 4, 6),
    ('alive',     0x54A238, 4, 4, 6),
    ('finish',    0x634C48, 4, 4, 6),
    ('lapmin',    0x634D54, 4, 4, 6),
    ('lapsec',    0x634D64, 4, 4, 6),
    ('laphun',    0x634D74, 4, 4, 6),
    ('rank',      0x456E18, 4, 4, 6),
    ('menu',      0x451FE0, 0x38, 11, 13),   # front-end item table: x,y,nav[4],on,sprite,cx,cy,state..
]
# loop bounds past a table's end that walk that table (instruction address, value)
EXTRA = [
    (0x004095C5, 0x456E28),   # race start: rank[i] = i for i < 4
    (0x00408421, 0x452268),   # main menu: copy home position to current, rows 0-10
    (0x0040E354, 0x45226C),   # rows 8-10
]
TEXT_VA, TEXT_RAW, TEXT_END = 0x401000, 0x400, 0x401000 + 242172
DATA_VA, DATA_RAW, DATA_RAWEND = 0x43F000, 250368, 0x43F000 + 150528


def which(v):
    for i, (n, b, e, c, _) in enumerate(TABLES):
        if b <= v < b + e * c:
            return i
    return None


def main():
    exe, dis, out = sys.argv[1:4]
    report = '--report' in sys.argv
    d = open(exe, 'rb').read()
    ins = []
    for l in open(dis, encoding='latin-1'):
        m = re.match(r'\s+([0-9A-F]{8}): (.*)', l)
        if m:
            ins.append((int(m.group(1), 16), m.group(2).strip()))
    sites, ends = [], []
    for k, (a, t) in enumerate(ins):
        if not (TEXT_VA <= a < TEXT_END):
            continue
        nxt = ins[k + 1][0] if k + 1 < len(ins) else a + 16
        if nxt - a > 16 or nxt <= a:
            continue
        raw = d[a - TEXT_VA + TEXT_RAW: nxt - TEXT_VA + TEXT_RAW]
        for o in range(0, len(raw) - 3):
            v = struct.unpack_from('<I', raw, o)[0]
            i = which(v)
            if i is not None:
                sites.append((a + o, v, i, t))
            else:
                for j, (n, b, e, c, _) in enumerate(TABLES):
                    if v == b + e * c and ('cmp' in t or 'mov' in t and 'h]' not in t):
                        ends.append((a, v, n, t))
    for at, v in EXTRA:
        k = next(k for k, (a, _) in enumerate(ins) if a == at)
        raw = d[at - TEXT_VA + TEXT_RAW: ins[k + 1][0] - TEXT_VA + TEXT_RAW]
        o = raw.find(struct.pack('<I', v))
        assert o >= 0, hex(at)
        i = next(i for i, t in enumerate(TABLES) if t[1] < v <= t[1] + t[2] * t[3] + t[2])
        sites.append((at + o, v, i, ins[k][1]))
    # pointers stored in initialised data
    dptr = []
    for o in range(DATA_RAW, DATA_RAW + (DATA_RAWEND - DATA_VA) - 3, 4):
        v = struct.unpack_from('<I', d, o)[0]
        if which(v) is not None:
            dptr.append((o - DATA_RAW + DATA_VA, v))
    with open(out, 'w') as f:
        f.write('/* generated by tools/sixcars/gen_relocs.py - do not edit */\n')
        f.write('#define RELOC_TABLES %d\n' % len(TABLES))
        for i, t in enumerate(TABLES):
            f.write('#define RT_%s %d\n' % (t[0].upper(), i))
        f.write('static const struct { const char *name; DWORD base, elem, oldn, newn; } '
                'g_rtab[RELOC_TABLES] = {\n')
        for n, b, e, c, nn in TABLES:
            f.write('  {"%s", 0x%X, 0x%X, %d, %d},\n' % (n, b, e, c, nn))
        f.write('};\n#define RELOC_SITES %d\n' % len(sites))
        f.write('static const struct { DWORD at, old; BYTE tab; } g_rsite[RELOC_SITES] = {\n')
        for at, v, i, t in sites:
            f.write('  {0x%06X, 0x%06X, %d},\n' % (at, v, i))
        f.write('};\n')
    per = {}
    for _, _, i, _ in sites:
        per[TABLES[i][0]] = per.get(TABLES[i][0], 0) + 1
    print('sites', len(sites), per)
    print('data pointers into tables:', [(hex(a), hex(v)) for a, v in dptr])
    print('end-address uses (review):')
    for a, v, n, t in ends:
        print(f'  {a:08X} {n:10s} {t}')
    if report:
        for at, v, i, t in sites:
            print(f'{at:08X} {TABLES[i][0]:10s} +{v - TABLES[i][1]:#06x}  {t}')


if __name__ == '__main__':
    main()
